/** コーチの判断に使う、今の状態 */
export interface CoachInput {
  turn: number;
  /** 予約に入っている行動の種類(move / attack / guard / carry / fireball / trip など。接近攻撃は attack) */
  plans: string[];
  /** 味方から敵が見えている */
  foeInSight: boolean;
  /** 誰かが気絶した味方を担いでいる */
  carrying: boolean;
  /** 立っている味方が、気絶した味方の隣にいる */
  besideDown: boolean;
}

export interface Lesson extends EncounterDef {
  /** 画面の上に出す、次にやること */
  steps: string[];
  /** 今のステップ(steps の番号)。状態から決まるので、順番通りに操作しなくても案内が追従する */
  coach: (c: CoachInput) => number;
  /** 開始時の一言 */
  intro: string;
  /** このレッスンで覚える操作(一覧に出す) */
  learn: string;
}

