export interface CoachInput {
  turn: number;
  /** 誰かが移動を予約している */
  hasMovePlan: boolean;
  /** 誰かが攻撃を予約している */
  hasAttackPlan: boolean;
  /** 味方から敵が見えている */
  foeInSight: boolean;
}

/** 練習戦の今のステップ(TUTORIAL_STEPS の番号)。状態から決まるので、順番通りでなくても迷わない */
export function coachStep(c: CoachInput): number {
  if (c.turn <= 1 && !c.foeInSight) return c.hasMovePlan ? 1 : 0;
  if (!c.foeInSight) return 2;
  return c.hasAttackPlan ? 4 : 3;
}
